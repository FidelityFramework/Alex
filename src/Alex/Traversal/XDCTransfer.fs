/// XDCTransfer — the pin facts the graph carries (Codata.Pins) written as XDC text
///
/// Architecturally parallel to MLIRTransfer. Both observe the same coeffects:
///   - MLIRTransfer: coeffects → MLIR ops (via witness traversal)
///   - XDCTransfer:  coeffects → XDC text (pure function, no traversal needed)
///
/// The coeffect IS the pre-computed data. This transfer is serialization.
///
/// Output: Xilinx XDC constraints file for Vivado synthesis.
module Alex.Traversal.XDCTransfer

open Fidelity.PSG

/// Generate constraint text from the graph's pin mapping.
/// Pure function: PinMapping → XDC text, or the pins whose direction the
/// coeffect did not settle to Input, Output or InOut (never silently dropped).
/// Port names are already normalized identifiers (computed in the coeffect).
let transfer (mapping: PinMapping) : Result<string, string> =
    let unsettled =
        mapping.Pins |> List.filter (fun p -> p.Direction <> "Input" && p.Direction <> "Output" && p.Direction <> "InOut")
    if not unsettled.IsEmpty then
        unsettled
        |> List.map (fun p -> sprintf "%s (direction '%s')" p.PortName p.Direction)
        |> String.concat ", "
        |> sprintf "PSG settlement (PlatformBindings.pins) did not settle an Input, Output or InOut direction for pins: %s"
        |> Result.Error
    else
        let clock = mapping.Clock
        let periodNs = 1_000_000_000.0 / float clock.FrequencyHz
        let groups =
            [ "Inputs", "Input"; "Outputs", "Output"; "Bidirectional", "InOut" ]
            |> List.choose (fun (heading, direction) ->
                let pins = mapping.Pins |> List.filter (fun pin -> pin.Direction = direction)
                if List.isEmpty pins then None
                else
                    Some ([ "# " + heading ] @
                          (pins |> List.collect (fun pin ->
                              [ sprintf "set_property PACKAGE_PIN %s [get_ports {%s}]" pin.PackagePin pin.PortName
                                sprintf "set_property IOSTANDARD %s [get_ports {%s}]" pin.IOStandard pin.PortName ]))))
        let reset =
            match mapping.Reset with
            | Some reset when reset.IsExternal ->
                [[ "# Reset"
                   sprintf "set_property PACKAGE_PIN %s [get_ports {%s}]" reset.PackagePin reset.PortName
                   sprintf "set_property IOSTANDARD %s [get_ports {%s}]" reset.IOStandard reset.PortName ]]
            | _ -> []
        [ [ sprintf "## Constraints for %s" mapping.DevicePart
            "## Generated by Composer from Fidelity.Platform pin definitions" ]
          [ "# Clock"
            sprintf "set_property PACKAGE_PIN %s [get_ports {%s}]" clock.PackagePin clock.PortName
            sprintf "set_property IOSTANDARD %s [get_ports {%s}]" clock.IOStandard clock.PortName
            sprintf "create_clock -add -name %s -period %.3f [get_ports {%s}]" clock.PortName periodNs clock.PortName ] ]
        @ reset @ groups
        |> List.map (String.concat "\n")
        |> String.concat "\n\n"
        |> Result.Ok
